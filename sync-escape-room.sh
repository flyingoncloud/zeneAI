#!/bin/bash
#
# Sync the Emotional Escape Room (情感密室) module into zeneAI.
#
#   ./sync-escape-room.sh [ESCAPE_REPO] [ZENEAI_ROOT]
#   defaults: ESCAPE_REPO=../Emotional-escape-room (branch Eltondev), ZENEAI_ROOT=.
#
# Re-run after a fresh drop of the escape-room repo (check out the Eltondev
# branch there first). Idempotent: overwrites the files it owns.
#
# Two tiers:
#   Backend  apps/api/app        -> ai-chat-api/src/escape   (FastAPI sub-app, mounted at /api/escape)
#   Frontend apps/web/src        -> zeneme-next/src          (routes under /escape-room, features in src/features)
#            apps/web/public/game-> zeneme-next/public/game
#
# It does NOT edit: ai-chat-api/src/api/app.py (mount block), requirements.txt,
# zeneme-next Sidebar/menu, or the scoped escape-room layout/CSS — those are
# one-time hand wiring. It verifies/warns about them at the end.
#
# TRANSFORMS applied to the copied frontend (the escape app assumes it owns "/"):
#   - page feature imports ../features -> @/features (depth-independent)
#   - nav paths /l2,/l3,/l4,/results,/,/?restart  ->  /escape-room/...
#   - API base  /api/v1  ->  /api/escape/api/v1   (matches the mounted sub-app)
#   - /game/* asset refs are left as-is (served from zeneme-next/public/game at root)

set -euo pipefail
RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; NC='\033[0m'
step(){ echo -e "\n${YELLOW}$*${NC}"; }
ok(){ echo -e "${GREEN}✓ $*${NC}"; }
warn(){ echo -e "${YELLOW}! $*${NC}"; }
die(){ echo -e "${RED}✗ $*${NC}" >&2; exit 1; }

ROOT="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
ESCAPE_REPO="${1:-$ROOT/../Emotional-escape-room}"
ZENE="${2:-$ROOT}"
SRC_API="$ESCAPE_REPO/apps/api"
SRC_WEB="$ESCAPE_REPO/apps/web"
[ -d "$SRC_WEB/src" ] || die "No apps/web/src under $ESCAPE_REPO (check out the Eltondev branch there)."
[ -d "$ZENE/zeneme-next/src" ] || die "No zeneme-next under $ZENE."

echo "Escape repo: $ESCAPE_REPO"
echo "zeneAI:      $ZENE"

# ---------------------------------------------------------------------------
step "Backend: apps/api/app -> ai-chat-api/src/escape"
BE="$ZENE/ai-chat-api/src/escape"
rm -rf "$BE"; mkdir -p "$BE"
cp -R "$SRC_API/app/." "$BE/"
cp -R "$SRC_API/migrations" "$BE/migrations"
cp "$SRC_API/alembic.ini" "$BE/alembic.ini"
# Upstream the package is "app"; here it is vendored flat at src/escape with
# alembic's prepend_sys_path=src/escape, so the migration env imports db directly.
perl -i -pe 's{^from app\.db import}{from db import}' "$BE/migrations/env.py"
ok "vendored src/escape (+ migrations, alembic.ini; env.py import rewritten)"

# ---------------------------------------------------------------------------
step "Frontend: features -> zeneme-next/src/features"
WD="$ZENE/zeneme-next/src"
rm -rf "$WD/features"; cp -R "$SRC_WEB/src/features" "$WD/features"
# drop unit tests (run via tsx upstream; they break next build's typecheck here)
find "$WD/features" \( -name '*.test.ts' -o -name '*.test.tsx' \) -delete
# vendor the one backend-shared config the web imports cross-tier
cp "$SRC_API/app/config/l2-overlap-masks.json" "$WD/features/l2/l2-overlap-masks.json"
ok "src/features (tests dropped, l2 masks vendored)"

step "Frontend: app routes -> zeneme-next/src/app/escape-room"
APP="$WD/app/escape-room"
rm -rf "$APP"; mkdir -p "$APP"
# route pages/dirs (NOT layout.tsx or globals.css — those are hand-scoped)
cp "$SRC_WEB/src/app/page.tsx" "$APP/page.tsx"
for d in l2 l3 l4 results; do cp -R "$SRC_WEB/src/app/$d" "$APP/$d"; done
cp "$SRC_WEB/src/app/icon.svg" "$APP/icon.svg" 2>/dev/null || true
for c in globals.css tokens.css game-prompts.css; do
  [ -f "$SRC_WEB/src/app/$c" ] && cp "$SRC_WEB/src/app/$c" "$APP/$c"
done
# Generated section layout. Importing the game's global CSS here (not the app
# root) makes Next code-split it to /escape-room/* only, so the host site is
# unaffected. The host root layout provides <html>/<body>; this only wraps.
# Generated by sync-escape-room.sh — hand edits are overwritten on re-sync.
cat > "$APP/layout.tsx" <<'LAYOUT'
import type { Metadata } from "next"
import { GameShell } from "@/features/cover/GameShell"
import "./globals.css"

export const metadata: Metadata = {
  title: "情感密室 · The Emotional Room",
  description: "一个关于你与爱的探索之旅。每一次选择，都是一次靠近真实的自己。",
  robots: { index: false, follow: false },
}

export default function EscapeRoomLayout({ children }: { children: React.ReactNode }) {
  return (
    <div className="escape-room-root">
      <GameShell>{children}</GameShell>
    </div>
  )
}
LAYOUT
ok "src/app/escape-room (pages + css + generated layout)"

step "Frontend: public/game -> zeneme-next/public/game"
rm -rf "$ZENE/zeneme-next/public/game"; cp -R "$SRC_WEB/public/game" "$ZENE/zeneme-next/public/game"
ok "public/game"

# ---------------------------------------------------------------------------
step "Rewriting paths in copied frontend"
# 1) page feature imports -> @/features (pages only; features keep relative imports)
find "$APP" -type f \( -name '*.tsx' -o -name '*.ts' \) -print0 | xargs -0 perl -i -pe '
  s{(\.\./)+features/}{\@/features/}g;
'
# 2) nav paths + API base, across pages AND features
find "$APP" "$WD/features" -type f \( -name '*.tsx' -o -name '*.ts' \) -print0 | xargs -0 perl -i -pe '
  s{(["'"'"'`])/api/v1}{$1/api/escape/api/v1}g;   # API base -> mounted sub-app
  s{(["'"'"'`])/l2}{$1/escape-room/l2}g;
  s{(["'"'"'`])/l3}{$1/escape-room/l3}g;
  s{(["'"'"'`])/l4}{$1/escape-room/l4}g;
  s{(["'"'"'`])/results}{$1/escape-room/results}g;
  s{href=(["'"'"'])/\?restart}{href=$1/escape-room?restart}g;
  s{(["'"'"'`])/\?restart}{$1/escape-room?restart}g;
  s{href="/"}{href="/escape-room"}g;
  s{href='"'"'/'"'"'}{href='"'"'/escape-room'"'"'}g;
  s{(===|!==|==) (["'"'"'])/\2}{$1 $2/escape-room$2}g;   # usePathname()==="/" (GameShell cover gate)
  s{(replaceState\([^,]*,[^,]*,\s*)(["'"'"'])/\2}{$1$2/escape-room$2}g;  # history.replaceState(...,"/")
'
# the web's l2 visual imports the masks json cross-tier; point it at the vendored copy
perl -i -pe 's{(["'"'"'])(\.\./)+api/app/config/l2-overlap-masks\.json}{$1./l2-overlap-masks.json}g' "$WD/features/l2/visual.ts"
ok "rewrote nav paths (/l2../results, /, /?restart), /api/v1 base, pathname gates, masks import"
warn "/game/* asset refs intentionally left as-is (served at root)"

# ---------------------------------------------------------------------------
step "Verify one-time hand wiring"
grep -q 'src.escape.main' "$ZENE/ai-chat-api/src/api/app.py" && ok "backend mount present in app.py" || warn "app.py missing the escape mount block"
grep -qi '^alembic' "$ZENE/ai-chat-api/requirements.txt" && ok "alembic in requirements" || warn "add alembic to ai-chat-api/requirements.txt"
[ -f "$APP/layout.tsx" ] && ok "escape-room/layout.tsx present (generated)" || warn "escape-room/layout.tsx missing (should have been generated)"
grep -q "escape-room" "$ZENE/zeneme-next/src/components/layout/Sidebar.tsx" && ok "menu entry present" || warn "add 情感密室 child to Sidebar.tsx"
ok "globals.css loads only on /escape-room/* (Next segment CSS code-splitting via the generated layout); not scoped by selector, so avoid rendering host components inside escape routes"

echo ""; ok "Sync complete. Build: (cd $ZENE/zeneme-next && npm run build)"
echo "   Backend migrations (once): (cd $ZENE/ai-chat-api/src/escape && DATABASE_URL=... alembic upgrade head)"
